CREATE TABLE groups (
  group_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_name VARCHAR(20) NOT NULL UNIQUE,
  specialty VARCHAR(100) NOT NULL,
  admission_year SMALLINT NOT NULL CHECK (admission_year BETWEEN 2000 AND 2100)
);
CREATE TABLE students (
  student_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  last_name VARCHAR(50) NOT NULL,
  first_name VARCHAR(50) NOT NULL,
  middle_name VARCHAR(50),
  birth_date DATE NOT NULL,
  group_id INT NOT NULL REFERENCES groups(group_id) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE TABLE teachers (
  teacher_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  last_name VARCHAR(50) NOT NULL,
  first_name VARCHAR(50) NOT NULL,
  department VARCHAR(100) NOT NULL
);
CREATE TABLE disciplines (
  discipline_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  discipline_name VARCHAR(100) NOT NULL UNIQUE,
  hours INT NOT NULL CHECK (hours > 0)
);
CREATE TABLE lessons (
  lesson_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id INT NOT NULL REFERENCES groups(group_id) ON UPDATE CASCADE ON DELETE CASCADE,
  discipline_id INT NOT NULL REFERENCES disciplines(discipline_id) ON UPDATE CASCADE ON DELETE CASCADE,
  teacher_id INT NOT NULL REFERENCES teachers(teacher_id) ON UPDATE CASCADE ON DELETE CASCADE,
  lesson_date DATE NOT NULL,
  lesson_type VARCHAR(30) NOT NULL CHECK (lesson_type IN ('Лекция','Практика','Лабораторная'))
);
CREATE TABLE grades (
  grade_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INT NOT NULL REFERENCES students(student_id) ON UPDATE CASCADE ON DELETE CASCADE,
  discipline_id INT NOT NULL REFERENCES disciplines(discipline_id) ON UPDATE CASCADE ON DELETE CASCADE,
  grade SMALLINT NOT NULL CHECK (grade BETWEEN 2 AND 5),
  grade_date DATE NOT NULL DEFAULT CURRENT_DATE
);
