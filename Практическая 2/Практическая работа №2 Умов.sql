CREATE OR REPLACE VIEW v_student_groups AS
SELECT s.student_id, s.last_name, s.first_name, s.middle_name, g.group_name, g.specialty
FROM students s JOIN groups g USING (group_id);
CREATE OR REPLACE VIEW v_full_schedule AS
SELECT l.lesson_id, g.group_name, d.discipline_name, t.last_name || ' ' || t.first_name AS teacher,
       l.lesson_date, l.lesson_type
FROM lessons l JOIN groups g USING (group_id)
JOIN disciplines d USING (discipline_id) JOIN teachers t USING (teacher_id);
CREATE OR REPLACE VIEW v_grade_summary AS
SELECT s.student_id, s.last_name || ' ' || s.first_name AS student,
       d.discipline_name, AVG(gr.grade)::numeric(3,2) AS average_grade, COUNT(*) AS grades_count
FROM grades gr JOIN students s USING (student_id)
JOIN disciplines d USING (discipline_id)
GROUP BY s.student_id,s.last_name,s.first_name,d.discipline_id,d.discipline_name;
CREATE INDEX idx_students_group_id ON students(group_id);
CREATE INDEX idx_lessons_teacher_date ON lessons(teacher_id,lesson_date);
CREATE INDEX idx_grades_student_discipline ON grades(student_id,discipline_id);
CREATE TABLE grade_audit (
  audit_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  grade_id INT NOT NULL,
  student_id INT NOT NULL,
  old_grade SMALLINT,
  new_grade SMALLINT NOT NULL,
  changed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE OR REPLACE FUNCTION validate_grade_and_audit() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.grade < 2 OR NEW.grade > 5 THEN
    RAISE EXCEPTION 'Оценка должна быть от 2 до 5';
  END IF;
  RETURN NEW;
END; $$;
CREATE TRIGGER trg_validate_grade
BEFORE INSERT OR UPDATE OF grade ON grades
FOR EACH ROW EXECUTE FUNCTION validate_grade_and_audit();
CREATE OR REPLACE FUNCTION log_grade_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO grade_audit(grade_id,student_id,old_grade,new_grade)
  VALUES (NEW.grade_id,NEW.student_id,CASE WHEN TG_OP='UPDATE' THEN OLD.grade ELSE NULL END,NEW.grade);
  RETURN NEW;
END; $$;
CREATE TRIGGER trg_audit_grade
AFTER INSERT OR UPDATE ON grades
FOR EACH ROW EXECUTE FUNCTION log_grade_change();
DO $$ BEGIN
 IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='teacher_role') THEN EXECUTE 'CREATE ROLE teacher_role NOLOGIN'; END IF;
